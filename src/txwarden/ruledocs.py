"""Human-readable rule documentation generated from the registry.

``txwarden explain`` / ``txwarden rules`` and ``docs/RULES.md`` (via ``scripts/gen_rules_doc.py``)
all render from ``rules.RULES`` and ``PolicyConfig`` defaults, so they cannot drift from the code;
a test fails if ``docs/RULES.md`` is stale.
"""
from __future__ import annotations

import textwrap
from typing import Any

from .risk import PolicyConfig
from .rules import RULES, RuleSpec

CATEGORY_ORDER = ["target", "approval", "operator", "permit", "transfer", "swap", "simulation",
                  "trace", "honeypot", "liquidity", "bundle"]
CATEGORY_TITLES = {
    "target": "Target and addresses", "approval": "ERC-20 approvals",
    "operator": "NFT operator approvals", "permit": "Signature permits",
    "transfer": "Transfers and recipients", "swap": "Swaps (price impact, slippage, MEV)",
    "simulation": "Simulation health", "trace": "Call tree", "honeypot": "Honeypot probe",
    "liquidity": "Liquidity removal", "bundle": "Cross-transaction (bundle) rules",
}


def knob_defaults() -> dict[str, Any]:
    return PolicyConfig().to_dict()


def fmt_default(value: Any) -> str:
    if isinstance(value, (list, set, tuple, dict)) and not value:
        return "empty"
    if isinstance(value, float):
        return f"{value:g}"
    return str(value)


def rules_by_category() -> dict[str, list[RuleSpec]]:
    out: dict[str, list[RuleSpec]] = {}
    for spec in RULES.values():
        out.setdefault(spec.category, []).append(spec)
    ordered = {c: out[c] for c in CATEGORY_ORDER if c in out}
    ordered.update({c: v for c, v in out.items() if c not in ordered})
    for specs in ordered.values():
        specs.sort(key=lambda r: (-int(r.severity), r.id))
    return ordered


def explain_text(spec: RuleSpec, width: int = 96) -> str:
    defaults = knob_defaults()
    lines = [f"{spec.id}  [{spec.severity.name} -> {spec.verdict.value}]  ({spec.category})",
             f"  {spec.title}", ""]
    for label, body in (("When it fires", spec.description), ("Why it matters", spec.docs)):
        if body:
            wrapped = textwrap.fill(body, width, initial_indent="    ", subsequent_indent="    ")
            lines += [f"  {label}:", wrapped, ""]
    if spec.config:
        lines.append("  Policy knobs (default):")
        lines += [f"    {k} = {fmt_default(defaults[k])}" for k in spec.config]
        lines.append("")
    lines.append(f"  Disable with: disabled_rules = [\"{spec.id}\"]")
    return "\n".join(lines)


def explain_dict(spec: RuleSpec) -> dict[str, Any]:
    defaults = knob_defaults()
    return {"rule": spec.id, "severity": spec.severity.name, "verdict": spec.verdict.value,
            "category": spec.category, "title": spec.title, "description": spec.description,
            "docs": spec.docs, "config": list(spec.config),
            "config_defaults": {k: defaults[k] for k in spec.config}}


def rules_table(specs: list[RuleSpec] | None = None) -> str:
    specs = specs if specs is not None else list(RULES.values())
    return "\n".join(f"{r.id:<36} {r.severity.name:<9} {r.verdict.value:<6} {r.title}"
                     for r in specs)


def markdown_summary_table() -> str:
    """The compact rule table used by README.md (id, severity -> verdict, title)."""
    rows = ["| Rule | Severity | Verdict | What it catches |", "|---|---|---|---|"]
    rows.extend(f"| `{r.id}` | {r.severity.name} | {r.verdict.value} | {r.title} |"
                for specs in rules_by_category().values() for r in specs)
    return "\n".join(rows)


def rules_markdown() -> str:
    defaults = knob_defaults()
    total = len(RULES)
    counts = {v: sum(1 for r in RULES.values() if r.verdict.value == v)
              for v in ("BLOCK", "WARN", "ALLOW")}
    out = [
        "# Rule reference",
        "",
        "<!-- Generated by scripts/gen_rules_doc.py from src/txwarden/rules.py. Do not edit. -->",
        "",
        f"TxWarden ships **{total} rules**. Severity is fixed per rule and decides the verdict: "
        f"**CRITICAL -> BLOCK** ({counts['BLOCK']} rules), **HIGH -> WARN** ({counts['WARN']} "
        f"rules), **MEDIUM and INFO -> ALLOW** ({counts['ALLOW']} rules, reported but never "
        "stopping). The verdict is the worst severity among the findings. "
        "Tune behaviour through the policy knobs listed under each rule (see "
        "[Configuration](../README.md#configuration)) or switch a rule off with "
        "`disabled_rules` (except `ENGINE_ERROR` and `SIMULATION_UNAVAILABLE`, which implement "
        "fail-closed behaviour and cannot be disabled).",
        "",
        "Use `txwarden rules` to list them and `txwarden explain <RULE>` for the text below.",
        "",
        "## Index",
        "",
        "| Rule | Severity | Verdict | Category |",
        "|---|---|---|---|",
    ]
    out.extend(f"| [`{r.id}`](#{r.id.lower()}) | {r.severity.name} | {r.verdict.value} | "
               f"{CATEGORY_TITLES.get(cat, cat)} |"
               for cat, specs in rules_by_category().items() for r in specs)
    for cat, specs in rules_by_category().items():
        out += ["", f"## {CATEGORY_TITLES.get(cat, cat)}"]
        for r in specs:
            out += ["", f"### {r.id}", "",
                    f"**{r.title}** - {r.severity.name} -> {r.verdict.value}", "",
                    f"*When it fires.* {r.description}"]
            if r.docs:
                out += ["", f"*Why it matters.* {r.docs}"]
            if r.config:
                out += ["", "*Policy knobs:* " + ", ".join(
                    f"`{k}` (default {fmt_default(defaults[k])})" for k in r.config)]
    return "\n".join(out).rstrip() + "\n"
